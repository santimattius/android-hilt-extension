@file:OptIn(DelicateTracingApi::class)

package io.github.santimattius.android.hilt.trace

import androidx.tracing.DelicateTracingApi
import androidx.tracing.Tracer

/**
 * Static tracing facade that instrumented bytecode calls.
 *
 * `Tracer.trace` is inline, so generated code cannot call it; these methods are plain static
 * entry points over [Tracer.global]. The `@DelicateTracingApi` opt-in is contained in this file.
 *
 * Threading contract: [begin] and the matching [end] must run on the same thread inside one
 * synchronous method, and pairs must nest in strict LIFO order. Closing the token pops the
 * innermost open slice of the current thread's track; there is no per-slice token.
 */
public object HiltTrace {

    /** Category of spans that cover the creation of a binding. */
    public const val CATEGORY_CREATE: String = "hilt.create"

    /** Category of spans that cover member injection and entry-point accessors. */
    public const val CATEGORY_INJECT: String = "hilt.inject"

    /**
     * Opens a slice and returns an opaque token for [end], or `null` when [category] is disabled
     * (including when no tracing driver is installed). A disabled category allocates nothing.
     *
     * The token is typed `Any?` so generated bytecode stores it as `java.lang.Object`; at runtime
     * it is an [AutoCloseable].
     */
    @JvmStatic
    public fun begin(category: String, name: String): Any? {
        // Never cache Tracer.global: the application installs the real tracer after startup.
        val tracer = Tracer.global
        if (!tracer.isCategoryEnabled(category)) return null
        val holder = tracer.beginSectionWithMetadata(category, name, null, false)
        // Without this call the sink would only ever see END events.
        holder.metadata.dispatchToTraceSink()
        // The holder is shared per track: read the closeable before any other tracing call.
        return holder.closeable
    }

    /** Closes the slice opened by the matching [begin]; a `null` token is a no-op. */
    @JvmStatic
    public fun end(token: Any?) {
        (token as AutoCloseable?)?.close()
    }

    /**
     * Builds the slice name `Type[@Qualifier]` so a trace shows which binding a slice belongs to.
     * A `null` or empty [qualifier] yields the bare [type].
     */
    @JvmStatic
    public fun sliceName(type: String, qualifier: String?): String =
        if (qualifier.isNullOrEmpty()) type else "$type@$qualifier"
}
